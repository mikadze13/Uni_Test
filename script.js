const questions = allQuestions
  .sort(() => Math.random() - 0.5)
  .slice(0, 30);

const form = document.getElementById("testForm");

questions.forEach((q, i) => {
  const div = document.createElement("div");
  div.className = "question";
  div.innerHTML = `<p>${q.question}</p>`;

  q.options.forEach((opt, j) => {
    div.innerHTML += `
          <label data-question="${i}" data-option="${j}">
            <input type="radio" name="q${i}" value="${j}">
            ${opt}
          </label><br>`;
  });

  form.appendChild(div);
});

document.getElementById("submitBtn").addEventListener("click", () => {
  let score = 0;
  const resultBox = document.getElementById("resultBox");
  resultBox.innerHTML = "";

  questions.forEach((q, i) => {
    const selected = document.querySelector(`input[name="q${i}"]:checked`);
    const labels = form.querySelectorAll(`label[data-question="${i}"]`);

    labels.forEach(label => {
      label.classList.remove("correct", "incorrect");
    });

    if (selected) {
      const answerIndex = parseInt(selected.value);
      if (answerIndex === q.correctIndex) {
        score++;
        labels[answerIndex].classList.add("correct");
      } else {
        labels[answerIndex].classList.add("incorrect");
        labels[q.correctIndex].classList.add("correct");
      }
    } else { 
      labels[q.correctIndex].classList.add("correct");
    }
  });

  let message = `შენი ქულაა: <span>${score}/${questions.length}</span><br>`;
  if (score < 20) {
    message += `<br><span style="color:red;">ვწუხვარ, დანძრეული გაქვთ!</span>`;
  } else {
    message += `<br><span style="color:green;">გილოცავ, გადასარევად გაართვი თავი!</span>`;
  }

  resultBox.innerHTML = message;
});
